/**
 * Material Design 3 Expressive (M3 Expressive) Web Component: <md-loading-indicator>
 *
 * Web adaptation referencing AndroidX Compose:
 * - androidx.compose.material3.LoadingIndicator.kt
 * - androidx.compose.material3.MaterialShapes.kt
 * - androidx.compose.material3.tokens.LoadingIndicatorTokens.kt
 *
 * Official Parameters & Token Parity:
 * - Container: 48x48dp, Shape: CornerFull (9999px)
 * - Active Indicator Size: 38x38dp
 * - Global Rotation Duration: 4666ms (Linear 360° infinite)
 * - Morph Interval: 650ms per shape transition
 * - Morph Step Rotation: +90° (QuarterRotation) per morph
 * - Spring Spec: dampingRatio = 0.6f, stiffness = 200f
 *
 * Geometry: matched cubic Bezier segments generated by the pinned AndroidX
 * graphics-shapes Morph implementation, not frame-sampled contours.
 */

import { observeThemeContext } from '../theme/theme-context.js';
import { LOADING_MORPHS } from '../tokens/loading-morphs.js';
import { drawMorph } from '../motion/cubic-morph.js';
import { SpringPhysics } from '../motion/spring-physics.js';
import { createComponentSheet, adoptSheet } from '../utils/styles.js';

const defaultStyle = `
  :host {
    -webkit-tap-highlight-color: transparent;
    -webkit-touch-callout: none;
    display: inline-block;
    vertical-align: middle;
    outline: none;
  }

  .loading-root {
    position: relative;
    width: 48px;
    height: 48px;
    box-sizing: border-box;
    display: inline-flex;
    align-items: center;
    justify-content: center;
    border-radius: var(--md-sys-shape-corner-full, 9999px);
    overflow: hidden;
    background-color: transparent;
  }

  :host([variant="contained"]) .loading-root {
    background-color: var(--md-sys-color-primary-container);
  }
  .color-probe { position: absolute; visibility: hidden; pointer-events: none; }

  canvas {
    display: block;
    width: 48px;
    height: 48px;
    pointer-events: none;
  }
`;

const loadingIndicatorSheet = createComponentSheet(defaultStyle);

const GLOBAL_ROTATION_DURATION = 4666; // 4666ms from LoadingIndicator.kt
const MORPH_INTERVAL = 650;           // 650ms from LoadingIndicator.kt
const QUARTER_ROTATION = 90;          // 90° per step

export class MdLoadingIndicator extends HTMLElement {
  static get observedAttributes() {
    return ['variant', 'size', 'progress', 'indeterminate', 'color', 'container-color', 'track-color', 'stroke-cap', 'gap-size', 'stroke-width'];
  }

  constructor() {
    super();
    this.attachShadow({ mode: 'open' });
    adoptSheet(this.shadowRoot, loadingIndicatorSheet);
    this._rendered = false;
    this._rafId = null;
    this._startTime = 0;
    this._currentMorphIndex = 0;
    this._lastStepTime = 0;
    this._cachedColor = null;
    this._colorDirty = true;
    this._observer = null;
    this._isVisible = true;
    this._motionPreference = matchMedia('(prefers-reduced-motion: reduce)');
    this._onMotionChange = () => this._startAnimation();
    this._onThemeChange = () => { this._colorDirty = true; if (this._motionPreference.matches || !this.indeterminate) this._startAnimation(); };
  }

  connectedCallback() {
    if (!this._rendered) {
      this.render();
      this._rendered = true;
    }
    this._colorDirty = true;
    this._stopThemeWatch = observeThemeContext(this, this._onThemeChange);
    this._motionPreference.addEventListener('change', this._onMotionChange);
    this._setupIntersectionObserver();
    this._startAnimation();
  }

  disconnectedCallback() {
    this._motionPreference.removeEventListener('change', this._onMotionChange);
    this._stopAnimation();
    if (this._observer) {
      this._observer.disconnect();
      this._observer = null;
    }
    this._stopThemeWatch?.();
    this._stopThemeWatch = null;
  }

  _setupIntersectionObserver() {
    if (typeof IntersectionObserver === 'undefined') return;
    this._observer = new IntersectionObserver((entries) => {
      const entry = entries[0];
      this._isVisible = entry ? entry.isIntersecting : true;
      if (this._isVisible) {
        if (!this._rafId) this._startAnimation();
      } else {
        this._stopAnimation();
      }
    }, { threshold: 0 });
    this._observer.observe(this);
  }

  attributeChangedCallback(name, oldVal, newVal) {
    if (!this._rendered || oldVal === newVal) return;
    if (name === 'color' || name === 'variant') {
      this._colorDirty = true;
    }
    if (name === 'progress' || name === 'indeterminate') {
      this._syncProgress();
    }
    this._updateDimensions();
    if (this._motionPreference.matches || !this.indeterminate || name === 'indeterminate' || name === 'progress') this._startAnimation();
  }

  _resolveActiveColor(isContained) {
    if (!this._colorDirty && this._cachedColor) {
      return this._cachedColor;
    }
    const colorAttr = this.getAttribute('color');
    const role = isContained ? 'on-primary-container' : 'primary';
    const color = ['primary','secondary','tertiary','on-primary-container'].includes(colorAttr)
      ? `var(--md-sys-color-${colorAttr})` : colorAttr && CSS.supports('color', colorAttr)
        ? colorAttr : `var(--md-sys-color-${role})`;
    this._probe.style.color = '';
    this._probe.style.color = color;
    this._cachedColor = getComputedStyle(this._probe).color;
    this._colorDirty = false;
    return this._cachedColor;
  }

  get variant() {
    return this.getAttribute('variant') || 'standalone'; // 'standalone' | 'contained'
  }
  get color() { return this.getAttribute('color') || ''; }
  set color(v) { if (v == null) this.removeAttribute('color'); else this.setAttribute('color', String(v)); }
  get containerColor() { return this.getAttribute('container-color') || ''; }
  set containerColor(v) { if (v == null) this.removeAttribute('container-color'); else this.setAttribute('container-color', String(v)); }
  set variant(v) {
    this.setAttribute('variant', v);
  }

  get size() {
    return this.getAttribute('size') || 'standard';
  }
  set size(v) {
    this.setAttribute('size', v);
  }

  get indeterminate() {
    return !this.hasAttribute('progress') || this.hasAttribute('indeterminate');
  }
  set indeterminate(v) {
    if (v) this.setAttribute('indeterminate', '');
    else this.removeAttribute('indeterminate');
  }

  get progress() {
    const p = parseFloat(this.getAttribute('progress'));
    return isNaN(p) ? null : Math.max(0, Math.min(1, p));
  }
  set progress(v) {
    if (v === null || v === undefined) this.removeAttribute('progress');
    else this.setAttribute('progress', String(v));
  }

  get trackColor() {
    return this.getAttribute('track-color') || 'var(--md-sys-color-secondary-container)';
  }
  set trackColor(v) {
    if (v === null || v === undefined) this.removeAttribute('track-color');
    else this.setAttribute('track-color', String(v));
  }

  get strokeCap() {
    return this.getAttribute('stroke-cap') || 'round';
  }
  set strokeCap(v) {
    if (v === null || v === undefined) this.removeAttribute('stroke-cap');
    else this.setAttribute('stroke-cap', String(v));
  }

  get gapSize() {
    const gs = parseFloat(this.getAttribute('gap-size'));
    return isNaN(gs) || gs < 0 ? 4.0 : gs;
  }
  set gapSize(v) {
    if (v === null || v === undefined) this.removeAttribute('gap-size');
    else this.setAttribute('gap-size', String(v));
  }

  get strokeWidth() {
    const sw = parseFloat(this.getAttribute('stroke-width'));
    return isNaN(sw) || sw <= 0 ? 4.0 : sw;
  }
  set strokeWidth(v) {
    if (v === null || v === undefined) this.removeAttribute('stroke-width');
    else this.setAttribute('stroke-width', String(v));
  }

  get sizePx() {
    const s = this.size;
    if (s === 'small') return 36;
    if (s === 'large') return 64;
    const n = parseInt(s, 10);
    return isNaN(n) ? 48 : Math.max(24, Math.min(128, n));
  }

  _startAnimation() {
    this._stopAnimation();
    if (!this.isConnected) return;
    this._startTime = performance.now();
    this._lastStepTime = this._startTime;
    this._currentMorphIndex = 0;

    const canvas = this.shadowRoot.querySelector('canvas');
    if (!canvas) return;
    const ctx = canvas.getContext('2d');
    if (this._motionPreference.matches || !this.indeterminate) {
      this._drawFrame(ctx, this._startTime + 650);
      return;
    }

    const loop = (now) => {
      this._drawFrame(ctx, now);
      this._rafId = requestAnimationFrame(loop);
    };
    this._rafId = requestAnimationFrame(loop);
  }

  _stopAnimation() {
    if (this._rafId) {
      cancelAnimationFrame(this._rafId);
      this._rafId = null;
    }
  }

  _drawFrame(ctx, now) {
    const canvas = ctx.canvas;
    const dpr = window.devicePixelRatio || 1;
    const sz = this.sizePx;
    const requiredW = Math.round(sz * dpr);
    const requiredH = Math.round(sz * dpr);

    // Keep physical buffer in sync with DPR on every frame to prevent zoom drifting
    if (canvas.width !== requiredW || canvas.height !== requiredH) {
      canvas.width = requiredW;
      canvas.height = requiredH;
      canvas.style.width = `${sz}px`;
      canvas.style.height = `${sz}px`;
    }

    ctx.save();
    ctx.setTransform(1, 0, 0, 1, 0, 0);
    ctx.clearRect(0, 0, canvas.width, canvas.height);

    ctx.setTransform(dpr, 0, 0, dpr, 0, 0);
    ctx.imageSmoothingEnabled = true;
    ctx.imageSmoothingQuality = 'high';
    ctx.lineCap = this.strokeCap;
    ctx.lineJoin = 'round';

    const center = sz / 2;
    const isContained = this.variant === 'contained';
    // AndroidX's rotation-safe polygon scale multiplied by ActiveSize / ContainerWidth.
    const sequence = this.indeterminate ? LOADING_MORPHS.indeterminate : LOADING_MORPHS.determinate;

    const isIndet = this.indeterminate;
    let pair;
    let morphT = 0;
    let globalAngle = 0;
    let stepAngle = 0;

    if (isIndet) {
      // 1. Continuous Global Rotation (4666ms period)
      const elapsedTotal = Math.max(0, now - this._startTime);
      globalAngle = ((elapsedTotal % GLOBAL_ROTATION_DURATION) / GLOBAL_ROTATION_DURATION) * 360;

      // Derive the step from elapsed time, avoiding per-frame timing drift.
      // Keep cumulative quarter-turns separate from the seven-shape index.
      const stepNumber = Math.floor(elapsedTotal / MORPH_INTERVAL);
      this._currentMorphIndex = stepNumber % sequence.morphs.length;
      this._lastStepTime = this._startTime + stepNumber * MORPH_INTERVAL;

      pair = sequence.morphs[this._currentMorphIndex];

      // Solve Compose Morph spring (damping: 0.6, stiffness: 200)
      const tNorm = Math.max(0, Math.min(1.0, (now - this._lastStepTime) / MORPH_INTERVAL));
      const springState = SpringPhysics.solve({
        from: 0,
        to: 1,
        dampingRatio: 0.6,
        stiffness: 200,
        mass: 1.0,
        time: tNorm * (MORPH_INTERVAL / 1000)
      });
      // Compose finishes the spring at its .1 visibility threshold, then holds
      // the next shape until the 650ms morph interval starts another spring.
      morphT = now - this._lastStepTime >= LOADING_MORPHS.morphDuration ? 1 : springState.position;

      // Quarter-rotation (+90°) per morph step
      stepAngle = (stepNumber + 1 + morphT) * QUARTER_ROTATION;
    } else {
      // Determinate Mode: Morphs from Circle to SoftBurst based on progress
      const p = this.progress || 0;
      pair = sequence.morphs[0];
      morphT = p;
      globalAngle = -p * 180;
      stepAngle = 0;
    }

    const totalAngle = ((globalAngle + stepAngle) * Math.PI) / 180;

    // Draw Morphed Shape
    ctx.translate(center, center);
    ctx.rotate(totalAngle);

    // Zero-Reflow Color Resolution
    ctx.fillStyle = this._resolveActiveColor(isContained);
    drawMorph(ctx, pair, morphT, sz * sequence.scale);
    ctx.restore();
  }

  _updateDimensions() {
    const root = this.shadowRoot.querySelector('.loading-root');
    const canvas = this.shadowRoot.querySelector('canvas');
    if (!root || !canvas) return;

    const sz = this.sizePx;
    root.style.width = `${sz}px`;
    root.style.height = `${sz}px`;
    root.style.backgroundColor = this.variant === 'contained' && CSS.supports('color', this.containerColor) ? this.containerColor : '';

    const dpr = window.devicePixelRatio || 1;
    canvas.width = sz * dpr;
    canvas.height = sz * dpr;
    canvas.style.width = `${sz}px`;
    canvas.style.height = `${sz}px`;
  }

  _syncProgress() {
    const root = this.shadowRoot.querySelector('.loading-root');
    if (!root) return;
    if (this.indeterminate) {
      root.setAttribute('aria-busy', 'true');
      root.removeAttribute('aria-valuenow');
    } else {
      root.setAttribute('aria-busy', 'false');
      root.setAttribute('aria-valuenow', String(Math.round((this.progress || 0) * 100)));
      root.setAttribute('aria-valuemin', '0');
      root.setAttribute('aria-valuemax', '100');
    }
  }

  render() {
    const hasAdopted = !!(this.shadowRoot.adoptedStyleSheets && this.shadowRoot.adoptedStyleSheets.length > 0);

    this.shadowRoot.innerHTML = `
      ${hasAdopted ? '' : `<style>${defaultStyle}</style>`}
      <div class="loading-root" role="progressbar" aria-label="Loading indicator">
        <canvas></canvas><span class="color-probe" aria-hidden="true"></span>
      </div>
    `;

    this._probe = this.shadowRoot.querySelector('.color-probe');
    this._updateDimensions();
    this._syncProgress();
  }
}

if (!customElements.get('md-loading-indicator')) {
  customElements.define('md-loading-indicator', MdLoadingIndicator);
}
